        public UsageGuideWindow()
        {
            InitializeComponent();
            Loaded += (s, e) =>
            {
                GuideListBox.SelectedIndex = 0; // 默认选中第一个模块
                ContentScrollViewer.ScrollToTop();
            };
        }

        private void GuideListBox_SelectionChanged(object sender, SelectionChangedEventArgs e)
        {
            if (GuideContentText == null) return;
            if (GuideListBox.SelectedItem == HazardItem)
                GuideContentText.Text = HazardGuide;
            else if (GuideListBox.SelectedItem == PersonnelItem)
                GuideContentText.Text = PersonnelGuide;
            else if (GuideListBox.SelectedItem == ProjectItem)
                GuideContentText.Text = ProjectGuide;
            else if (GuideListBox.SelectedItem == ImageViewerItem)
                GuideContentText.Text = ImageViewerGuide;
            else if (GuideListBox.SelectedItem == ImportExportItem)
                GuideContentText.Text = ImportExportGuide;
            else if (GuideListBox.SelectedItem == LanItem)
                GuideContentText.Text = LanGuide;
            else if (GuideListBox.SelectedItem == CreateTableItem)
                GuideContentText.Text = CreateTableGuide;

            // 仅「创建标准表格」栏显示示例图片
            if (CreateTableExamplePanel != null)
                CreateTableExamplePanel.Visibility =
                    GuideListBox.SelectedItem == CreateTableItem ? Visibility.Visible : Visibility.Collapsed;

            ContentScrollViewer?.ScrollToTop();
        }

